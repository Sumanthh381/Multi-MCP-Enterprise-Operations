import asyncio
import json
from pathlib import Path

import httpx

from enterprise.registry import Registry

ROOT = Path(__file__).resolve().parents[1]


async def main():
    r = await Registry().connect()
    entries = []
    examples = {}
    events = []
    try:
        alarm = (
            await r.call("alarm.get_alarms", {"asset_id": "BFP-101"}, "catalog-export", events)
        )["data"][0]["alarm_id"]
        examples = {
            "search_assets": {"query": "Boiler Feed Pump 101"},
            "asset_metadata": {"asset_id": "BFP-101"},
            "get_alarms": {"asset_id": "BFP-101", "page_size": 1},
            "alarm_detail": {"alarm_id": alarm},
            "alarm_summary": {"request": {"asset_ids": ["BFP-101"]}},
            "alarm_trends": {"request": {"asset_ids": ["BFP-101"]}},
            "correlate_alarms": {"request": {"asset_ids": ["BFP-101"]}},
            "flood_analysis": {"request": {"unit": "Unit 2"}},
            "rationalization_candidates": {"request": {"asset_ids": ["BFP-101"]}},
            "priority_score": {"request": {"alarm_id": alarm}},
            "operator_recommendations": {"request": {"alarm_id": alarm}},
            "generate_calculation": {
                "request": {"calculation_type": "operator_response_efficiency"}
            },
            "kpi_definitions": {},
            "maintenance_history": {"asset_id": "BFP-101"},
            "prepare_issue_draft": {
                "asset_id": "BFP-101",
                "title": "Investigate BFP-101",
                "evidence": "Recurring vibration [SOP-PUMP-101:1:0]",
            },
        }
        mappings = {
            "search_assets": "GET /assets/search",
            "asset_metadata": "GET /assets/{asset_id}/metadata",
            "get_alarms": "GET /alarms",
            "alarm_detail": "GET /alarms/{alarm_id}",
            "alarm_summary": "POST /alarms/summary",
            "alarm_trends": "POST /alarms/trends",
            "correlate_alarms": "POST /alarms/correlation",
            "flood_analysis": "POST /alarms/flood-analysis",
            "rationalization_candidates": "POST /alarms/rationalization-candidates",
            "priority_score": "POST /alarms/priority-score",
            "operator_recommendations": "POST /recommendations/operator-actions",
            "generate_calculation": "POST /calculation-code/generate",
            "execute_calculation": "POST /calculation-code/execute",
            "kpi_definitions": "GET /analytics/kpi-definitions",
            "maintenance_history": "SQLite SELECT maintenance",
            "prepare_issue_draft": "SQLite INSERT draft (no ticket creation)",
            "create_ticket": "SQLite INSERT ticket (explicit confirmation, idempotent by draft)",
        }
        for tool in r.catalog():
            name = tool["name"]
            if name == "execute_calculation":
                definition = await r.call(
                    "alarm.generate_calculation",
                    examples["generate_calculation"],
                    "catalog-export",
                    events,
                )
                examples[name] = {"request": {"calculation_id": definition["calculation_id"]}}
            if name == "create_ticket":
                # Document the mandatory confirmation rejection without creating anything.
                example = {"draft_id": "example-draft", "confirmed": False}
                output = {"isError": True, "message": "Explicit user confirmation required"}
            else:
                example = examples[name]
                data = await r.call(tool["key"], example, "catalog-export", events)
                output = {
                    "data": data,
                    "trace_id": "catalog-export",
                    "api_status": 200,
                    "retries": 0,
                }
            entries.append(
                f"## `{tool['key']}`\n\n{tool['description']}\n\nSource operation: `{mappings[name]}`.\n\nInput schema:\n```json\n{json.dumps(tool['inputSchema'], indent=2)}\n```\n\nOutput schema:\n```json\n{json.dumps(tool['outputSchema'], indent=2)}\n```\n\nExample invocation:\n```json\n{json.dumps({'name': name, 'arguments': example}, indent=2)}\n```\n\nExample response (captured from the simulator; may be abbreviated in GUI):\n```json\n{json.dumps(output, indent=2)}\n```\n"
            )
        header = """# MCP tool catalog

Generated by `python scripts/export_docs.py` from real MCP discovery and tool execution.

Both servers use official MCP stdio JSON-RPC with initialization, `tools/list` and `tools/call`. Every invocation validates the discovered input schema, the discovered output schema and the Pydantic output envelope. `data` is a JSON object with operation-specific fields shown in the captured responses; the shared envelope does not enforce every domain payload field.

Shared behavior for **every alarm tool**: source authentication is a bearer token from `ALARM_API_TOKEN`, sent only by the alarm connector. HTTP 401/403/404/422 map to readable tool errors; response bodies are not copied into errors. HTTP 429/502/503/504 and network/timeouts retry at most twice (100/200 ms backoff). Per-attempt source timeout defaults to 5 seconds, MCP call deadline to 20 seconds. No retry is made after an uncertain ticket write. Trace metadata is forwarded as MCP `_meta.trace_id`, tool `trace_id`, and API `trace_id`, with client and metadata headers. The output carries status and retry count. No credentials appear in results.

Shared behavior for **every workorders tool**: local stdio process ownership is the authorization boundary; SQLite queries are parameterized. The backend only exposes a confirmation route for a draft owned by the current conversation. MCP clients launched independently are trusted local operators and must enforce their own approval boundary. Missing drafts and unconfirmed writes produce MCP errors. Calls use the same 20-second client deadline, with no automatic write retry. Database persistence is local; there is no GitHub ticket write integration.

Independent startup: `.venv/bin/python -m enterprise.alarm_mcp` and `.venv/bin/python -m enterprise.workorders_mcp` (stdio; connect an MCP client, do not expect an HTTP page).

"""
        (ROOT / "docs/mcp-tool-catalog.md").write_text(header + "\n".join(entries))
        (ROOT / "docs/tool-schemas.json").write_text(json.dumps(r.catalog(), indent=2))
        (ROOT / "docs/alarm-openapi.json").write_text(
            json.dumps(httpx.get("http://127.0.0.1:8000/openapi.json").json(), indent=2)
        )
    finally:
        await r.close()


if __name__ == "__main__":
    asyncio.run(main())
